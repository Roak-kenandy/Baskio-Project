-- One-time MySQL setup. Run as an administrative MySQL user:
--   mysql -u root -p < scripts/mysql-setup.sql
-- Replace CHANGE_ME_STRONG_PASSWORD below with the same value as DB_PASSWORD in backend/.env before running.

CREATE DATABASE IF NOT EXISTS BAISKOAFU CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE USER IF NOT EXISTS 'BAISKOAFU'@'localhost' IDENTIFIED BY 'CHANGE_ME_STRONG_PASSWORD';
CREATE USER IF NOT EXISTS 'BAISKOAFU'@'127.0.0.1' IDENTIFIED BY 'CHANGE_ME_STRONG_PASSWORD';

-- Least privilege: only this database, no GRANT/FILE/SUPER rights.
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, INDEX, REFERENCES ON BAISKOAFU.* TO 'BAISKOAFU'@'localhost';
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, INDEX, REFERENCES ON BAISKOAFU.* TO 'BAISKOAFU'@'127.0.0.1';

FLUSH PRIVILEGES;
